export function formatDate(iso) {
  return new Date(`${iso}T12:00:00`).toLocaleDateString("fr-FR", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

/**
 * Publication programmée : un article n'est visible (blog, page, sitemap) qu'à
 * partir de sa date, évaluée à l'heure de Paris. Les pages du blog et le
 * sitemap sont régénérés toutes les heures (ISR), donc chaque article sort
 * tout seul le jour prévu, sans redéploiement.
 */
export function todayInParis(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Paris" }).format(now);
}

export function getPublishedArticles(today = todayInParis()) {
  return allArticles.filter((a) => a.date <= today);
}

export function getArticle(slug) {
  return getPublishedArticles().find((a) => a.slug === slug);
}

export function getRelated(article, count = 3) {
  const published = getPublishedArticles();
  const same = published.filter((a) => a.slug !== article.slug && a.category === article.category);
  const others = published.filter((a) => a.slug !== article.slug && a.category !== article.category);
  return [...same, ...others].slice(0, count);
}

